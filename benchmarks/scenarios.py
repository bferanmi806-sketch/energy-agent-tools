SCENARIO_CASES: tuple[ScenarioCase, ...] = FIXTURE_CASES + PENDING_CASES


def discovery_intents(
    scenarios: Sequence[ScenarioCase] = SCENARIO_CASES,
) -> tuple[DiscoveryIntent, ...]:
    """Return scenario-derived and separately reviewed discovery queries."""

    category_capabilities = {
        "baseline_fixture": "get_energy_consumption",
        "consumption": "get_energy_consumption",
        "tariff": "estimate_electricity_cost",
        "renewables": "get_solar_generation",
        "storage": "get_battery_state",
        "carbon": "get_carbon_intensity",
        "grid": "get_grid_generation",
        "weather_building": "get_building_weather",
        "ev_demand_response": "get_ev_state",
        "connections": "list_connections",
        "data_quality": "report_timeseries_coverage",
        "engineering": "run_power_flow",
    }
    derived = tuple(
        DiscoveryIntent(
            id=f"scenario_{case.id}",
            query=case.prompt,
            capability=category_capabilities.get(case.category, case.intent),
            category=case.category,
            split=case.split,
            provider_hints=(case.provider,),
            expected_tools=case.expected.expected_tools or ("ENERGY_RESOLVE_CAPABILITY",),
            expected_terms=tuple(group[0] for group in case.expected.required_terms),
            origin="scenario",
        )
        for case in scenarios
    )
    return derived + REVIEWED_DISCOVERY_INTENTS


def scenario_cases() -> tuple[ScenarioCase, ...]:
    """Return the immutable ordered corpus."""

    return SCENARIO_CASES


def corpus_manifest(cases: Sequence[ScenarioCase] = SCENARIO_CASES) -> dict[str, Any]:
    """Build a deterministic manifest suitable for review and CI artifacts."""

    discovery = discovery_intents(cases)
    split_counts = {
        split: sum(case.split == split for case in cases) for split in ("development", "heldout")
    }
    status_counts = {
        status: sum(case.status == status for case in cases)
        for status in ("executable_fixture", "pending_environment")
    }
    category_counts = {
        category: sum(case.category == category for case in cases)
        for category in sorted({case.category for case in cases})
    }
    provider_counts = {
        provider: sum(case.provider == provider for case in cases)
        for provider in sorted({case.provider for case in cases})
    }
    return {
        "schema_version": "scenario-corpus-v1",
        "total_cases": len(cases),
        "split_counts": split_counts,
        "status_counts": status_counts,
        "category_counts": category_counts,
        "provider_counts": provider_counts,
        "executable_fixture_ids": [case.id for case in cases if case.executable],
        "pending_environment_ids": [case.id for case in cases if not case.executable],
        "source_fixture_case_ids": sorted(EXISTING_FIXTURE_CASE_IDS),
        "heldout_is_pending": all(
            case.status == "pending_environment" for case in cases if case.split == "heldout"
        ),
        "discovery_intent_count": len(discovery),
        "discovery_split_counts": {
            split: sum(intent.split == split for intent in discovery)
            for split in ("development", "heldout")
        },
        "reviewed_discovery_intent_count": sum(
            intent.origin == "reviewed_query" for intent in discovery
        ),
    }


def export_corpus(
    output: Path, cases: Sequence[ScenarioCase] = SCENARIO_CASES
) -> tuple[Path, Path]:
    """Write ``scenario-corpus.jsonl`` and ``manifest.json`` to ``output``."""

    output.mkdir(parents=True, exist_ok=True)
    corpus_path = output / "scenario-corpus.jsonl"
    discovery_path = output / "discovery-intents.jsonl"
    manifest_path = output / "manifest.json"
    corpus_path.write_text(
        "".join(json.dumps(case.to_json(), sort_keys=True) + "\n" for case in cases),
        encoding="utf-8",
    )
    discovery_path.write_text(
        "".join(
            json.dumps(intent.to_json(), sort_keys=True) + "\n"
            for intent in discovery_intents(cases)
        ),
        encoding="utf-8",
    )
    manifest_path.write_text(
        json.dumps(corpus_manifest(cases), indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )
    return corpus_path, manifest_path


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--output", type=Path, required=True, help="directory for JSONL and manifest"
    )
    args = parser.parse_args(argv)
    corpus_path, manifest_path = export_corpus(args.output)
    print(f"exported {len(SCENARIO_CASES)} scenarios to {corpus_path}")
    print(f"wrote manifest to {manifest_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
