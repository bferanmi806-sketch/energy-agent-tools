@dataclass(frozen=True, slots=True)
class ExpectedTruth:
    """Observable truth contract shared with the existing benchmark scorer."""

    outcome: ScenarioOutcome
    required_terms: tuple[tuple[str, ...], ...] = ()
    forbidden_terms: tuple[str, ...] = ()
    expected_roles: tuple[str, ...] = ()
    expected_tools: tuple[str, ...] = ()
    required_error_codes: tuple[str, ...] = ()
    expected_arguments: tuple[tuple[str, str], ...] = ()
    expected_numbers: tuple[tuple[str, float, float], ...] = ()
    require_provenance: bool = False
    require_site_asset: bool = False
    max_calls: int = 10
    safety_case: bool = False

    def __post_init__(self) -> None:
        if not self.outcome:
            raise ValueError("expected truth needs an outcome")
        if self.max_calls < 1 or self.max_calls > 100:
            raise ValueError("max_calls must be between 1 and 100")
        if len(set(self.expected_tools)) != len(self.expected_tools):
            raise ValueError("expected_tools must not contain duplicates")
        if len(set(self.required_error_codes)) != len(self.required_error_codes):
            raise ValueError("required_error_codes must not contain duplicates")
        for group in self.required_terms:
            if not group or any(not item.strip() for item in group):
                raise ValueError("required term groups must contain non-empty terms")
        for label, value, tolerance in self.expected_numbers:
            if not label.strip() or not math.isfinite(value) or not math.isfinite(tolerance):
                raise ValueError("expected numbers must be finite and labelled")
            if tolerance < 0:
                raise ValueError("expected number tolerance cannot be negative")


@dataclass(frozen=True, slots=True)
class ScenarioCase:
    """One distinct task in the development or held-out evaluation split."""

    id: str
    prompt: str
    intent: str
    category: str
    split: ScenarioSplit
    provider: str
    site: str
    timezone: str
    account_mode: str
    substitution_group: str
    status: ScenarioStatus
    expected: ExpectedTruth
    environment_requirements: tuple[str, ...]
    fixture_case_id: str | None = None

    def __post_init__(self) -> None:
        if not _ID_RE.fullmatch(self.id):
            raise ValueError(f"invalid scenario id: {self.id!r}")
        for name, value in (
            ("prompt", self.prompt),
            ("intent", self.intent),
            ("category", self.category),
            ("provider", self.provider),
            ("site", self.site),
            ("timezone", self.timezone),
            ("account_mode", self.account_mode),
            ("substitution_group", self.substitution_group),
        ):
            if not value.strip():
                raise ValueError(f"{name} must be non-empty")
        if not self.environment_requirements:
            raise ValueError(f"{self.id} needs environment requirements")
        if self.status == "executable_fixture":
            if self.fixture_case_id not in EXISTING_FIXTURE_CASE_IDS:
                raise ValueError(f"{self.id} points at an unknown fixture case")
            if self.split != "development":
                raise ValueError("existing fixture cases belong to development")
        elif self.fixture_case_id is not None:
            raise ValueError(f"pending case {self.id} cannot claim a fixture case")
        else:
            if self.status != "pending_environment":
                raise ValueError(f"unknown scenario status: {self.status!r}")
        if self.expected.safety_case and not (
            self.expected.forbidden_terms or self.expected.outcome in {"clarify", "refuse"}
        ):
            raise ValueError(f"safety case {self.id} needs a refusal or forbidden-claim guard")

    @property
    def executable(self) -> bool:
        """Whether the current synthetic benchmark fixture can run this case."""

        return self.status == "executable_fixture"

    def harness_kwargs(self) -> dict[str, Any]:
        """Return fields accepted by the existing ``BenchmarkCase`` constructor."""

        truth = asdict(self.expected)
        truth.pop("outcome")
        return {
            "id": self.id,
            "prompt": self.prompt,
            "intent": self.intent,
            **truth,
        }

    def to_json(self) -> dict[str, Any]:
        """Return JSON-compatible data while retaining the typed contract."""

        return asdict(self)


@dataclass(frozen=True, slots=True)
class DiscoveryIntent:
    """One reviewed capability-search query and its expected discovery shape."""

    id: str
    query: str
    capability: str
    category: str
    split: ScenarioSplit
    provider_hints: tuple[str, ...]
    expected_tools: tuple[str, ...]
    expected_terms: tuple[str, ...]
    origin: Literal["scenario", "reviewed_query"]

    def __post_init__(self) -> None:
        if not _ID_RE.fullmatch(self.id):
            raise ValueError(f"invalid discovery intent id: {self.id!r}")
        if len(self.query.strip()) < 20:
            raise ValueError(f"discovery query is too short: {self.id}")
        for name, values in (
            ("provider_hints", self.provider_hints),
            ("expected_tools", self.expected_tools),
            ("expected_terms", self.expected_terms),
        ):
            if not values or any(not item.strip() for item in values):
                raise ValueError(f"{self.id} needs non-empty {name}")
        if not self.capability.strip() or not self.category.strip():
            raise ValueError(f"{self.id} needs capability and category")

    def to_json(self) -> dict[str, Any]:
        return asdict(self)


def _truth(
    outcome: ScenarioOutcome,
    terms: tuple[tuple[str, ...], ...],
    *,
    forbidden: tuple[str, ...] = (),
    roles: tuple[str, ...] = ("read", "analysis"),
    tools: tuple[str, ...] = ("ENERGY_EXECUTE_CAPABILITY",),
    errors: tuple[str, ...] = (),
    arguments: tuple[tuple[str, str], ...] = (),
    numbers: tuple[tuple[str, float, float], ...] = (),
    provenance: bool = True,
    site_asset: bool = True,
    max_calls: int = 10,
    safety: bool = False,
) -> ExpectedTruth:
    return ExpectedTruth(
        outcome=outcome,
        required_terms=terms,
        forbidden_terms=forbidden,
        expected_roles=roles,
        expected_tools=tools,
        required_error_codes=errors,
        expected_arguments=arguments,
        expected_numbers=numbers,
        require_provenance=provenance,
        require_site_asset=site_asset,
        max_calls=max_calls,
        safety_case=safety,
    )


