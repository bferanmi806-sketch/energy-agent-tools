"""Versioned agent-scenario corpus for the Energy Agent Tools roadmap.

This module is deliberately additive.  It does not change the live benchmark
harness or claim that pending scenarios are executable against its small
synthetic fixture.  Each :class:`ScenarioCase` carries the same observable
scoring fields as ``benchmarks.harness.BenchmarkCase`` plus evaluation metadata
for split, provider/site substitution, and environment readiness.

Export a deterministic JSONL corpus and manifest with::

    python work/roadmap-evaluation/benchmarks/scenarios.py \
        --output work/roadmap-evaluation/export
"""

